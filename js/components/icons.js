/**
 * Devolve o markup de um ícone.
 * O `size` vem em px; a cor é sempre herdada do texto (currentColor).
 */
export function icon(name, size = 20) {
  const paths = PATHS[name];
  if (!paths) {
    console.warn(`Ícone desconhecido: "${name}"`);
    return '';
  }

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${paths}</svg>`;
}

/** Mesma coisa, já como elemento. */
export function iconElement(name, size = 20) {
  const wrapper = document.createElement('span');
  wrapper.className = 'icon';
  wrapper.innerHTML = icon(name, size);
  return wrapper.firstElementChild;
}
